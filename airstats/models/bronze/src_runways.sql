WITH RAW_RUNWAYS AS 
(
    --SELECT * FROM AIRBNB.RAW.RAW_HOSTS
    SELECT * FROM {{source('airstats','runways')}}
)

SELECT 
ID AS RUNWAY_ID,
AIRPORT_IDENT,
LENGTH_FT AS RUNWAY_LENGTH_FT,
WIDTH_FT AS RUNWAY_WIDTH_FT,
SURFACE AS RUNWAY_SURFACE,
LIGHTED AS RUNWAY_LIGHTED,
CLOSED AS RUNWAY_CLOSED
FROM RAW_RUNWAYS
ORDER BY ID